#include<stdio.h>            // 引入标准输入输出库，使用 printf
void swap(int*x,int*y){      // 定义交换函数：参数是指针（int*），void 表示不需要返回值
	int t=*x;                 // *x 解引用，取出指针 x 指向的值（即 a 的值）暂存到临时变量 t
	*x=*y;                    // 把 y 指向的值（即 b 的值）赋给 x 指向的变量，此时 a 变成了 b 原来的值
	*y=t;                     // 把暂存的 t 赋给 y 指向的变量，此时 b 拿到 a 原来的值，交换完成
	
}



int main(){                  // 主函数，程序入口，返回 int 状态码
	int a=10,b=20;            // 定义两个整型变量 a=10、b=20，准备演示交换
	printf("交换前a=%d, b=%d\n",a,b);  // 打印交换前的 a 和 b，%d 依次对应后面的 a、b
	swap(&a,&b);               // 调用 swap，传的是地址 &a、&b（传址调用），函数内部才能真正修改 a、b
	printf("交换后a=%d, b=%d\n",a,b);  // 打印交换后的 a 和 b，验证交换是否成功
	return 0;                 // 返回 0，表示程序正常结束
	
	
} 

